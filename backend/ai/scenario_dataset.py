"""Scenario Dataset Builder Module for Quantum City.

Coordinates multiple SUMO world simulations across diverse multiverse scenarios
generated by ScenarioManager and WorldGenerator, sequentially executing simulations
via TrafficSimulator and aggregating real TrafficSimulationResult runs for supervised
training of the TrafficPredictionModel.
"""

from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple, Union
import numpy as np
from pydantic import BaseModel, ConfigDict, Field

from ai.traffic_model import TrafficDatasetBuilder
from multiverse.scenario_manager import ScenarioManager, World
from multiverse.world_generator import WorldGenerator
from simulation.traffic import TrafficSimulationResult, TrafficSimulator


class ScenarioDatasetStatistics(BaseModel):
    """Aggregated statistics of multi-scenario simulation datasets."""
    model_config = ConfigDict(extra="ignore")

    number_of_worlds: int = Field(description="Number of distinct city scenarios simulated")
    number_of_simulation_runs: int = Field(description="Total number of simulation runs executed")
    total_observations: int = Field(description="Total step observations collected across all runs")
    total_supervised_transitions: int = Field(
        description="Total transition pairs (X_t -> y_{t+1}) available for machine learning training"
    )
    world_ids: List[str] = Field(default_factory=list, description="List of world IDs included in dataset")
    world_names: List[str] = Field(default_factory=list, description="List of world names included in dataset")


class ScenarioDatasetBuilder:
    """Manages multi-world simulation execution and dataset compilation for AI training."""

    def __init__(
        self,
        scenario_manager: Optional[ScenarioManager] = None,
        simulator: Optional[TrafficSimulator] = None,
        sumo_config_path: Optional[Union[str, Path]] = None,
    ) -> None:
        """Initialize ScenarioDatasetBuilder.

        Args:
            scenario_manager: Optional ScenarioManager instance; creates new if omitted.
            simulator: Optional TrafficSimulator instance; creates default if omitted.
            sumo_config_path: Optional explicit path to .sumocfg configuration file.
        """
        self.scenario_manager = scenario_manager if scenario_manager is not None else ScenarioManager()
        self.world_generator = WorldGenerator(scenario_manager=self.scenario_manager)
        self.simulator = simulator if simulator is not None else TrafficSimulator(default_config_path=sumo_config_path)
        self.sumo_config_path = sumo_config_path

        self._simulation_results: List[TrafficSimulationResult] = []
        self._simulated_worlds: List[World] = []

    @property
    def simulation_results(self) -> List[TrafficSimulationResult]:
        """Return the collected list of simulation results."""
        return list(self._simulation_results)

    @property
    def simulated_worlds(self) -> List[World]:
        """Return the list of worlds simulated in this dataset."""
        return list(self._simulated_worlds)

    def run_worlds(
        self,
        worlds: Sequence[World],
        steps: int = 100,
        step_length: float = 1.0,
        gui: bool = False,
    ) -> List[TrafficSimulationResult]:
        """Sequentially execute SUMO simulations for a given sequence of worlds.

        Args:
            worlds: Sequence of World scenario objects to simulate.
            steps: Number of simulation steps per world (default 100).
            step_length: Simulation step length in seconds (default 1.0).
            gui: Whether to launch graphical interface (default False for headless).

        Returns:
            List of collected TrafficSimulationResult objects.
        """
        results: List[TrafficSimulationResult] = []

        for world in worlds:
            sim_result = self.simulator.run_simulation(
                steps=steps,
                step_length=step_length,
                gui=gui,
                sumo_config_path=self.sumo_config_path,
                world=world,
            )
            results.append(sim_result)
            self._simulation_results.append(sim_result)
            self._simulated_worlds.append(world)

        return results

    def run_predefined_worlds(
        self,
        steps: int = 100,
        step_length: float = 1.0,
        gui: bool = False,
    ) -> List[TrafficSimulationResult]:
        """Generate and sequentially run simulations for all predefined worlds.

        Predefined worlds executed:
          1. Baseline 2030 (world_baseline_2030)
          2. Eco Future 2030 (world_eco_future_2030)
          3. Smart Mobility 2030 (world_smart_mobility_2030)

        Args:
            steps: Number of simulation steps per scenario (default 100).
            step_length: Step duration in seconds (default 1.0).
            gui: Headless by default (False).

        Returns:
            List of TrafficSimulationResult objects for the 3 predefined scenarios.
        """
        predefined = self.world_generator.generate_predefined_worlds()
        return self.run_worlds(
            worlds=predefined,
            steps=steps,
            step_length=step_length,
            gui=gui,
        )

    def get_dataset_statistics(self) -> ScenarioDatasetStatistics:
        """Compute summary statistics for the accumulated multi-scenario dataset.

        Returns:
            ScenarioDatasetStatistics model containing counts and world metadata.
        """
        total_obs = sum(len(res.step_observations) for res in self._simulation_results)
        # Each simulation run with N observations yields N - 1 transition pairs
        total_transitions = sum(
            max(0, len(res.step_observations) - 1)
            for res in self._simulation_results
        )

        world_ids = [w.world_id for w in self._simulated_worlds]
        world_names = [w.name for w in self._simulated_worlds]

        return ScenarioDatasetStatistics(
            number_of_worlds=len(set(world_ids)),
            number_of_simulation_runs=len(self._simulation_results),
            total_observations=total_obs,
            total_supervised_transitions=total_transitions,
            world_ids=world_ids,
            world_names=world_names,
        )

    def build_training_matrices(
        self,
        speed_limit: float = 13.9,
    ) -> Tuple[np.ndarray, np.ndarray]:
        """Convert collected simulation results into supervised ML feature and target matrices.

        Delegates directly to TrafficDatasetBuilder in traffic_model.py for feature
        extraction and target computation across all multi-world runs.

        Args:
            speed_limit: Speed limit in m/s used for congestion normalization (default 13.9).

        Returns:
            Tuple of (X, y) as numpy arrays.
        """
        return TrafficDatasetBuilder.build_dataset(
            self._simulation_results,
            speed_limit=speed_limit,
        )
